import AppKit

enum ClipCapture {
    case text(String)
    case image(Data) // PNG data
}

final class ClipboardMonitor {
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    var onCapture: ((ClipCapture) -> Void)?

    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.check()
        }
        timer?.tolerance = 0.1
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        // Skip password managers / transient content
        if let types = pb.types, types.contains(where: { ClipboardMonitor.ignoredTypes.contains($0) }) {
            return
        }

        // Skip writes made by Clippy itself
        if PasteService.isSelfWrite(changeCount: pb.changeCount) { return }

        // Prefer image over text (screenshots often include both)
        if let imageData = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            guard imageData.count <= 20 * 1024 * 1024 else { return }
            guard let png = ClipboardMonitor.asPNG(imageData) else { return }
            onCapture?(.image(png))
        } else if let str = pb.string(forType: .string), !str.isEmpty {
            guard str.utf8.count <= 1024 * 1024 else { return }
            // Ignore whitespace-only strings
            guard !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            onCapture?(.text(str))
        }
    }

    private static func asPNG(_ data: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: data) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
