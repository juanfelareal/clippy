// Monitor del portapapeles (port de ClipboardMonitor.swift + PasteService.swift).
// API de portapapeles de Electron 44+: asíncrona, basada en ClipboardItem (W3C).
// Windows: el helper de PowerShell avisa cada cambio real (GetClipboardSequenceNumber), así no se
// lee el portapapeles en vano. Sin helper (dev en macOS o si falla): sondeo cada 500 ms.
const { clipboard, ClipboardItem, nativeImage } = require('electron');
const { History } = require('./history');

const RAW = 'electron application/osclipboard;format=';
const rawName = type => (type.startsWith(RAW) ? type.slice(RAW.length).replace(/^"|"$/g, '') : null);

// Formatos que marcan contenido privado / que no debe ir a historiales
const EXCLUDE_FORMATS = new Set([
  // Windows (gestores de contraseñas, apps que piden no ser monitoreadas)
  'ExcludeClipboardContentFromMonitorProcessing', 'Clipboard Viewer Ignore',
  // macOS (nspasteboard.org) — solo para desarrollo
  'org.nspasteboard.TransientType', 'org.nspasteboard.ConcealedType', 'org.nspasteboard.AutoGeneratedType', 'com.agilebits.onepassword'
]);

const MAX_TEXT_BYTES = 1024 * 1024;
const MAX_IMAGE_PIXELS = 20 * 1024 * 1024; // ~20 MP

async function blobToBuffer(blob) { return Buffer.from(await blob.arrayBuffer()); }

class ClipboardMonitor {
  constructor({ history, helper, log = () => {} }) {
    this.history = history;
    this.helper = helper;
    this.log = log;
    this.selfWrites = new Map(); // hash → expira (ms)
    this.lastSignature = null;
    this.timer = null;
    this.pending = false;
    this.running = false;
    this.rerun = false;
  }

  async start() {
    // Estado inicial: lo que ya estaba copiado no entra al historial
    this.lastSignature = await this.signature();
    if (this.helper && process.platform === 'win32') {
      this.helper.on('clipboard', seq => {
        // El primer valor solo establece la línea base
        if (this.lastSeq === undefined) { this.lastSeq = seq; return; }
        if (seq === this.lastSeq) return;
        this.lastSeq = seq;
        this.schedule();
      });
    }
    // Respaldo / macOS: sondeo
    this.timer = setInterval(async () => {
      if (this.helper && this.helper.available) return;
      if (this.running) return;
      const sig = await this.signature();
      if (sig !== this.lastSignature) { this.lastSignature = sig; this.process(); }
    }, 500);
  }

  stop() { clearInterval(this.timer); }

  // Debounce corto: las apps suelen escribir varios formatos seguidos
  schedule() {
    if (this.pending) return;
    this.pending = true;
    setTimeout(() => { this.pending = false; this.process(); }, 120);
  }

  async readItem() {
    const items = await clipboard.read();
    return items && items.length ? items[0] : null;
  }

  // Firma barata para el sondeo de respaldo
  async signature() {
    try {
      const item = await this.readItem();
      if (!item) return '';
      let extra = '';
      const imgType = item.types.find(t => t.startsWith('image/'));
      if (imgType) { const b = await item.getType(imgType); extra = `${imgType}:${b.size}`; }
      const text = item.types.includes('text/plain') ? await (await item.getType('text/plain')).text() : '';
      return item.types.join(',') + '|' + text + '|' + extra;
    } catch { return ''; }
  }

  markSelfWrite(hash) {
    const now = Date.now();
    for (const [h, exp] of this.selfWrites) if (exp < now) this.selfWrites.delete(h);
    this.selfWrites.set(hash, now + 4000);
  }

  isSelfWrite(hash) { const exp = this.selfWrites.get(hash); return !!exp && exp >= Date.now(); }

  async isConcealed(item) {
    for (const type of item.types) {
      const name = rawName(type);
      if (!name) continue;
      if (EXCLUDE_FORMATS.has(name)) return true;
      // Windows: CanIncludeInClipboardHistory = DWORD 0 → no guardar
      if (name === 'CanIncludeInClipboardHistory') {
        try {
          const buf = await blobToBuffer(await item.getType(type));
          if (buf.length >= 4 && buf.readUInt32LE(0) === 0) return true;
        } catch {}
      }
    }
    return false;
  }

  async process() {
    if (this.running) { this.rerun = true; return; }
    this.running = true;
    try {
      const item = await this.readItem();
      if (!item) return;
      if (await this.isConcealed(item)) { this.log('clipboard: contenido privado ignorado'); return; }
      // Imagen primero (las capturas suelen traer también texto)
      const imgType = item.types.find(t => t === 'image/png') || item.types.find(t => t.startsWith('image/'));
      if (imgType) {
        const img = nativeImage.createFromBuffer(await blobToBuffer(await item.getType(imgType)));
        if (!img.isEmpty()) {
          const { width, height } = img.getSize();
          if (width * height > MAX_IMAGE_PIXELS) return;
          const hash = History.imageHash(img);
          if (this.isSelfWrite(hash)) return;
          this.history.addImage(img, hash);
          return;
        }
      }
      if (!item.types.includes('text/plain')) return;
      const text = await (await item.getType('text/plain')).text();
      if (!text || !text.trim()) return;
      if (Buffer.byteLength(text, 'utf8') > MAX_TEXT_BYTES) return;
      const hash = History.textHash(text);
      if (this.isSelfWrite(hash)) return;
      this.history.addText(text, hash);
    } catch (e) {
      this.log('clipboard process error', String(e && e.stack || e));
    } finally {
      this.running = false;
      this.lastSignature = await this.signature();
      if (this.rerun) { this.rerun = false; this.process(); }
    }
  }

  // ---- Escrituras propias (no vuelven a entrar al historial) ----
  async writeTextSilently(text) {
    this.markSelfWrite(History.textHash(text));
    await clipboard.writeText(text);
    this.lastSignature = await this.signature();
  }

  async writeImageSilently(img) {
    this.markSelfWrite(History.imageHash(img));
    await clipboard.write([new ClipboardItem({ 'image/png': new Blob([img.toPNG()], { type: 'image/png' }) })]);
    this.lastSignature = await this.signature();
  }

  // Guardar / restaurar el portapapeles completo (snippets) — igual que Hablapp
  async snapshot() {
    try {
      const items = await clipboard.read();
      const saved = [];
      for (const item of items) {
        const payload = {};
        for (const type of item.types) {
          if (type === 'electron application/bookmark' || type === 'electron application/findtext') continue;
          try { payload[type] = await item.getType(type); } catch {}
        }
        if (Object.keys(payload).some(t => !t.startsWith('electron application/'))) saved.push(payload);
      }
      return saved;
    } catch (e) {
      this.log('clipboard snapshot failed', String(e));
      return null;
    }
  }

  async restore(saved) {
    try {
      if (!saved || !saved.length) { await clipboard.clear(); return; }
      for (const payload of saved) {
        if (payload['text/plain']) this.markSelfWrite(History.textHash(await payload['text/plain'].text()));
        const imgType = Object.keys(payload).find(t => t.startsWith('image/'));
        if (imgType) {
          const img = nativeImage.createFromBuffer(await blobToBuffer(payload[imgType]));
          if (!img.isEmpty()) this.markSelfWrite(History.imageHash(img));
        }
      }
      await clipboard.write(saved.map(p => new ClipboardItem(p)));
    } catch (e) {
      this.log('clipboard restore failed', String(e));
    }
    this.lastSignature = await this.signature();
  }
}

module.exports = { ClipboardMonitor };
